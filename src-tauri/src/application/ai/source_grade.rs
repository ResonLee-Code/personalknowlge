/// 内容里出现这些标记 → 判 E（AI 生成 / 不可判定出处）。
const AI_MARKERS: &[&str] = &[
    "由 ai 生成",
    "ai 生成",
    "ai-generated",
    "generated by ai",
    "chatgpt 生成",
    "本内容由 chatgpt",
    "内容由 ai",
];

/// 给一个外部来源分级。
///
/// - `url`：最终地址（可以是裸域名）
/// - `title` / `snippet`：用于内容自证（是否有标题、作者、日期）
pub fn grade_web(url: &str, title: &str, snippet: &str) -> Grade {
    let host = host_of(url);
    let title = title.trim();
    let haystack = format!("{} {}", title, snippet).to_lowercase();

    if let Some(marker) = AI_MARKERS.iter().find(|marker| haystack.contains(**marker)) {
        return Grade::new(
            SourceLevel::E,
            format!("内容自证为 AI 生成（命中 `{marker}`），只作线索"),
        );
    }

    if let Some(host) = host.as_deref() {
        if let Some((rule, level)) = longest_match(host) {
            return Grade::new(level, format!("域名 {host} 命中内置分级表（{rule}）"));
        }
    }

    // 内容自证：有标题 + 有日期或作者标识 → C；否则 D
    if !title.is_empty() && (has_date(&haystack) || has_author(&haystack)) {
        return Grade::new(
            SourceLevel::C,
            "未命中分级表，但标题与日期/作者齐全，按「一般」处理".to_string(),
        );
    }
    if title.is_empty() {
        return Grade::new(SourceLevel::E, "页面没有可用标题，无法判定出处，只作线索");
    }
    Grade::new(
        SourceLevel::D,
        "未命中分级表，且缺少日期与作者标识，按「弱」处理",
    )
}

/// 给一篇本地笔记分级：优先用笔记自己的 `source_reliability`（用户标注过的口径）。
pub fn grade_local_note(source_reliability: Option<i64>, source_type: Option<&str>) -> Grade {
    if let Some(value) = source_reliability {
        let level = SourceLevel::from_reliability(value);
        return Grade::new(
            level,
            format!("沿用笔记已标注的 source_reliability={value}"),
        );
    }
    // 没有标注时按「个人推测」以外的来源类型给一个保守档
    match source_type.unwrap_or("").trim() {
        "official" => Grade::new(SourceLevel::B, "来源类型为 official，但未标注可靠性"),
        "book" => Grade::new(SourceLevel::B, "来源类型为 book，但未标注可靠性"),
        "experiment" => Grade::new(SourceLevel::C, "来源类型为 experiment（自测数据）"),
        "personal" => Grade::new(SourceLevel::D, "来源类型为 personal（个人推测）"),
        _ => Grade::new(
            SourceLevel::D,
            "笔记未标注 source_reliability：按「弱」处理（建议在笔记里补标注）",
        ),
    }
}

/// 时效判定：来源发布时间早于「今天 − 时间窗」→ 可能已过时。
///
/// 缺发布日期时返回 `None`（报告中标「时效未知」，而不是假装新鲜）。
pub fn is_stale(published_at: Option<&str>, time_window_days: u32) -> Option<bool> {
    let published = published_at?;
    let age_days = days_between(published, &crate::core::time::today_date())?;
    Some(age_days > i64::from(time_window_days))
}

/// 取 host（小写、去 www、去端口）。
pub fn host_of(url: &str) -> Option<String> {
    let trimmed = url.trim();
    if trimmed.is_empty() {
        return None;
    }
    let rest = trimmed
        .split_once("://")
        .map(|(_, rest)| rest)
        .unwrap_or(trimmed);
    let host = rest
        .split(['/', '?', '#'])
        .next()
        .unwrap_or("")
        .rsplit('@')
        .next()
        .unwrap_or("")
        .split(':')
        .next()
        .unwrap_or("")
        .trim()
        .trim_start_matches("www.")
        .to_ascii_lowercase();
    if host.is_empty() {
        None
    } else {
        Some(host)
    }
}

/// 域名表匹配：规则命中 host 本身或它的某个父域，取最长（最具体）的规则。
fn longest_match(host: &str) -> Option<(&'static str, SourceLevel)> {
    DOMAIN_TABLE
        .iter()
        .filter(|(rule, _)| host == *rule || host.ends_with(&format!(".{rule}")))
        .max_by_key(|(rule, _)| rule.len())
        .copied()
}

fn has_date(value: &str) -> bool {
    // 形如 2024-01-31 / 2024/01/31 / 2024年1月
    let chars: Vec<char> = value.chars().collect();
    for index in 0..chars.len().saturating_sub(3) {
        if !chars[index..index + 4].iter().all(char::is_ascii_digit) {
            continue;
        }
        let mut cursor = index + 4;
        let mut segments = 1;
        while segments < 3 {
            if cursor >= chars.len() || !matches!(chars[cursor], '-' | '/' | '年') {
                break;
            }
            cursor += 1;
            let start = cursor;
            while cursor < chars.len() && chars[cursor].is_ascii_digit() {
                cursor += 1;
            }
            if cursor == start {
                break;
            }
            segments += 1;
        }
        if segments >= 2 {
            return true;
        }
    }
    false
}

fn has_author(value: &str) -> bool {
    ["作者", "author", "by ", "编者", "审校"].iter().any(|marker| value.contains(marker))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn built_in_table_grades_known_domains_and_prefers_specific_rule() {
        assert_eq!(grade_web("https://doc.rust-lang.org/book/", "目录", "").level, SourceLevel::A);
        assert_eq!(
            grade_web("https://blog.rust-lang.org/2024/01/01/x.html", "发布", "").level,
            SourceLevel::B,
            "更长后缀优先：blog.rust-lang.org 命中 B 而不是 A"
        );
        assert_eq!(grade_web("https://www.zhihu.com/question/1", "问答", "").level, SourceLevel::D);
        assert_eq!(grade_web("https://twitter.com/x/status/1", "帖子", "").level, SourceLevel::E);
    }

    #[test]
    fn unknown_domains_fall_back_to_content_self_evidence() {
        let dated = grade_web("https://blog.example.dev/post", "某技术的实践", "2024-05-01 发布");
        assert_eq!(dated.level, SourceLevel::C);
        assert!(dated.reason.contains("一般"));

        let bare = grade_web("https://blog.example.dev/post", "某技术的实践", "随手记录");
        assert_eq!(bare.level, SourceLevel::D);

        let untitled = grade_web("https://blog.example.dev/post", "   ", "");
        assert_eq!(untitled.level, SourceLevel::E);
    }

    #[test]
    fn ai_generated_markers_force_level_e_even_on_trusted_domains() {
        let grade = grade_web("https://docs.rs/tokio", "说明", "以下内容由 AI 生成，仅供参考");
        assert_eq!(grade.level, SourceLevel::E);
        assert!(grade.reason.contains("AI 生成"));
    }

    #[test]
    fn local_notes_prefer_explicit_reliability_then_source_type() {
        assert_eq!(grade_local_note(Some(5), None).level, SourceLevel::A);
        assert_eq!(grade_local_note(Some(2), None).level, SourceLevel::D);
        assert_eq!(grade_local_note(None, Some("official")).level, SourceLevel::B);
        assert_eq!(grade_local_note(None, Some("personal")).level, SourceLevel::D);
        let unknown = grade_local_note(None, None);
        assert_eq!(unknown.level, SourceLevel::D);
        assert!(unknown.reason.contains("建议"));
    }

    #[test]
    fn staleness_needs_a_publish_date() {
        assert_eq!(is_stale(None, 730), None, "无日期 → 时效未知");
        assert_eq!(is_stale(Some("2026-10-01"), 730), Some(false), "近 10 天不算过时");
        assert_eq!(is_stale(Some("2000-01-01"), 730), Some(true));
    }
}
