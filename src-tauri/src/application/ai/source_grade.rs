//!
//! **纯函数**：不联网、不依赖模型，因此可单测、可复核。
//! 判定顺序（与文档一致）：域名/机构内置分级表 → 内容自证（标题/作者/日期）→ 兜底 D。
//! —— 用户配置的白名单/黑名单在 `policy.rs` 里先过一遍（黑名单强制丢弃、白名单非空时只放行其中域名）。

