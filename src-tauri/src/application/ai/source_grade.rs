/// 分级结果：级别 + **可读的判定理由**（理由会写进报告，便于用户核对而不是盲信）。
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Grade {
    pub level: SourceLevel,
    pub reason: String,
}

impl Grade {
    fn new(level: SourceLevel, reason: impl Into<String>) -> Self {
        Self { level, reason: reason.into() }
    }
}

